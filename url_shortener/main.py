"""HTTP API for the local URL-shortener reference application."""
import os
from contextlib import asynccontextmanager
from fastapi import FastAPI
from fastapi.responses import RedirectResponse
from .db import initialize
from .models import CreateUrlRequest, UrlResponse, AnalyticsResponse
from .service import create_url, get_url, analytics

@asynccontextmanager
async def lifespan(app: FastAPI):
    initialize()
    yield

app = FastAPI(
    title="URL Shortener API",
    version="1.0.0",
    description="Reference API generated by the agentic engineering workflow.",
    lifespan=lifespan,
)

@app.post("/api/v1/urls", response_model=UrlResponse, status_code=201)
def create(request: CreateUrlRequest):
    row = create_url(str(request.original_url), request.custom_alias, request.expires_at)
    public_base_url = os.getenv("SHORTENER_PUBLIC_BASE_URL", "http://localhost:8001").rstrip("/")
    return {
        "short_code": row["short_code"],
        "short_url": f"{public_base_url}/{row['short_code']}",
        "original_url": row["original_url"],
        "created_at": row["created_at"],
        "expires_at": row["expires_at"],
    }

@app.get("/{code}", response_class=RedirectResponse, responses={302: {"description": "Redirect"}, 404: {"description": "Unknown code"}, 410: {"description": "Expired URL"}})
def redirect(code: str):
    row = get_url(code)
    return RedirectResponse(row["original_url"], status_code=302)

@app.get("/api/v1/urls/{code}/analytics", response_model=AnalyticsResponse)
def get_analytics(code: str):
    return analytics(code)
